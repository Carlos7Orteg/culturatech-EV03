package com.culturatech.culturatechev03.model;

// Importaciones de las anotaciones JPA utilizadas para mapear la clase con la tabla categoria.
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * Entidad que representa las categorÃ­as de los eventos.
 * Corresponde a la tabla categoria de la base de datos.
 */
@Entity
@Table(name = "categoria")
public class Categoria {

    // Atributos de la categorÃ­a y mÃ©todos de acceso para su gestiÃ³n mediante JPA.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id_categoria")
    private Integer idCategoria;

    @Column(name = "nombre_categoria", nullable = false, length = 100)
    private String nombreCategoria;

    @Column(name = "descripcion", length = 255)
    private String descripcion;

    // MÃ©todos de acceso para consultar y modificar los datos de la categorÃ­a.
    public Integer getIdCategoria() {
        return idCategoria;
    }

    public void setIdCategoria(Integer idCategoria) {
        this.idCategoria = idCategoria;
    }

    public String getNombreCategoria() {
        return nombreCategoria;
    }

    public void setNombreCategoria(String nombreCategoria) {
        this.nombreCategoria = nombreCategoria;
    }

    public String getDescripcion() {
        return descripcion;
    }

    public void setDescripcion(String descripcion) {
        this.descripcion = descripcion;
    }
}
